"""Verifier (and demo generator) for the AEGIS reference text watermark.

The reference watermark is the published green-list scheme (Kirchenbauer et al., 2023) applied to
a public pseudo-word vocabulary, keyed by a deployment secret. It exists so that the verification
pathway (keyed detection, exact p-values, minimum-length checks, key secrecy) is genuinely
exercised end-to-end. It can only verify text produced by the AEGIS reference generator with the
same key. It is not a detector for any commercial model's watermark.
"""

from __future__ import annotations

import hashlib
import os
import re

import numpy as np
from aegis_research.watermark import GreenListWatermark, SyntheticLM, WatermarkConfig, generate

from aegis_ml.core import (
    AnalysisInput,
    AnalysisMethod,
    EvidenceClass,
    ImplementationStatus,
    MethodInfo,
    MethodResult,
    Modality,
    RunStatus,
)

VOCAB_SIZE = 2048
_CONS = "bdfgklmnprstvzhj"
_VOWELS = "aeiou"


def _build_vocab() -> list[str]:
    syll = [c + v for c in _CONS for v in _VOWELS]
    words = sorted({a + b for a in syll for b in syll})
    rng = np.random.default_rng(20240501)  # public, fixed: the vocabulary is not secret
    order = rng.permutation(len(words))[:VOCAB_SIZE]
    return [words[i] for i in order]


VOCAB = _build_vocab()
_INDEX = {w: i for i, w in enumerate(VOCAB)}


def token_ids(text: str) -> list[int]:
    ids = []
    for w in re.findall(r"[a-z]+", text.lower()):
        i = _INDEX.get(w)
        if i is None:  # out-of-vocabulary words map deterministically (public hash) into the id space
            i = int.from_bytes(hashlib.sha256(w.encode()).digest()[:4], "big") % VOCAB_SIZE
        ids.append(i)
    return ids


def _config() -> WatermarkConfig:
    return WatermarkConfig(vocab_size=VOCAB_SIZE, gamma=0.25, delta=2.0, context_width=1)


def generate_reference_text(key: bytes, n_tokens: int, seed: int, watermarked: bool = True) -> str:
    """Pseudo-word text from a toy model; output is meaningless by design (demo/benchmark only)."""
    lm = SyntheticLM(VOCAB_SIZE, zipf_exponent=1.0, seed=seed)
    rng = np.random.default_rng(seed)
    mark = GreenListWatermark(key, _config()) if watermarked else None
    toks = generate(lm, n_tokens, rng, mark, start_token=int(rng.integers(VOCAB_SIZE)))
    words = [VOCAB[t] for t in toks]
    out, sentence = [], []
    for i, w in enumerate(words):
        sentence.append(w)
        if len(sentence) >= 12 or i == len(words) - 1:
            out.append(" ".join(sentence).capitalize() + ".")
            sentence = []
    return " ".join(out)


class ReferenceWatermarkVerifier(AnalysisMethod):
    info = MethodInfo(
        id="watermark.aegis_reference_text",
        name="AEGIS reference text watermark verifier",
        version="1.0.0",
        modalities=(Modality.TEXT, Modality.DOCUMENT),
        evidence_class=EvidenceClass.VERIFIED_WATERMARK,
        implementation=ImplementationStatus.OPERATIONAL,
        description=(
            "Keyed green-list z-test (Kirchenbauer et al., 2023) for text generated by the AEGIS "
            "reference generator under this deployment's key."
        ),
        output_semantics=(
            "z-score and exact binomial p-value for the null hypothesis 'not watermarked with this key'. "
            "'Watermark detected' means the reference watermark for THIS key is present."
        ),
        limitations=(
            "Only verifies the AEGIS reference watermark; cannot detect watermarks of commercial models.",
            "Absence of this watermark says nothing about whether text is AI-generated or human-written.",
            "Detection weakens with editing, paraphrasing and short length.",
        ),
        references=("Kirchenbauer et al. (2023), A Watermark for Large Language Models, ICML.",),
        requires=("AEGIS_REFERENCE_WATERMARK_KEY",),
    )

    def __init__(self, key: bytes | None = None, z_threshold: float = 4.0) -> None:
        env = os.environ.get("AEGIS_REFERENCE_WATERMARK_KEY", "")
        self._key = key if key is not None else (env.encode() if env else None)
        self.z_threshold = z_threshold

    def availability(self) -> tuple[bool, str]:
        if not self._key or len(self._key) < 16:
            return False, "Reference watermark key not configured (AEGIS_REFERENCE_WATERMARK_KEY, >=16 bytes)."
        return True, "available"

    def _run(self, inp: AnalysisInput) -> MethodResult:
        assert self._key is not None
        mark = GreenListWatermark(self._key, _config())
        det = mark.detect(token_ids(inp.text or ""), self.z_threshold, dedupe=True)
        out = det.to_dict() | {"key_fingerprint": mark.key_fingerprint, "vocabulary": f"aegis-pseudoword-{VOCAB_SIZE}"}
        cfg = {"gamma": mark.config.gamma, "z_threshold": self.z_threshold, "dedupe_pairs": True}
        if not det.sufficient_length:
            return self.result(
                RunStatus.INSUFFICIENT_INPUT,
                f"Only {det.scored_tokens} scorable tokens; too short to test for the watermark.",
                output=out,
                config=cfg,
            )
        summary = (
            f"Reference watermark detected (z={det.z_score:.2f}, exact p={det.p_value_exact:.2e})."
            if det.detected
            else f"Reference watermark not detected (z={det.z_score:.2f}). This does not indicate human authorship."
        )
        return self.result(
            RunStatus.COMPLETED,
            summary,
            output=out,
            score=det.z_score,
            score_semantics="z-score under H0 (not watermarked with this key)",
            flagged=det.detected,
            config=cfg,
            uncertainty={"p_value_exact": det.p_value_exact, "p_value_normal_approx": det.p_value_normal_approx},
        )


class SynthIDTextAdapter(AnalysisMethod):
    """Integration boundary for Google DeepMind SynthID-Text. Verification requires the provider's
    watermarking configuration (keys) and a trained Bayesian detector that are not public."""

    info = MethodInfo(
        id="watermark.synthid_text",
        name="SynthID-Text watermark verification",
        version="0.0.0",
        modalities=(Modality.TEXT, Modality.DOCUMENT),
        evidence_class=EvidenceClass.VERIFIED_WATERMARK,
        implementation=ImplementationStatus.PLACEHOLDER,
        description="Placeholder for an authorised SynthID-Text verification integration.",
        output_semantics="Would report the provider detector's verdict for the provider's keys.",
        limitations=("Not implemented: requires provider keys and detector weights under an agreement.",),
        references=("Dathathri et al. (2024), Scalable watermarking for identifying LLM outputs, Nature.",),
        requires=("provider agreement", "watermarking keys", "detector weights"),
    )

    def availability(self) -> tuple[bool, str]:
        return False, "No authorised SynthID-Text verification integration is configured."

    def _run(self, inp: AnalysisInput) -> MethodResult:  # pragma: no cover - never available
        raise RuntimeError("unavailable")
